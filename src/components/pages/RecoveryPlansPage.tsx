import React, { useState, useEffect } from 'react';
import { GitBranch, RefreshCw, CheckCircle2, AlertTriangle, ArrowRight } from 'lucide-react';
import { apiClient, RecoveryPlanRecord, DisruptionRecord, ApprovalRecord } from '../../services/apiClient';
import { useApp } from '../../context/AppContext';
import { PageHeader } from '../common/PageHeader';
import { DataTable, Column } from '../common/DataTable';
import { StatusBadge } from '../common/StatusBadge';
import { RecordDrawer } from '../common/RecordDrawer';
import { useToast } from '../common/Toast';

export const RecoveryPlansPage: React.FC = () => {
  const { seedFixtures, selectedRecordId, setSelectedRecordId, navigateToRecord, refreshData } = useApp();
  const { showToast } = useToast();
  const [plans, setPlans] = useState<RecoveryPlanRecord[]>([]);
  const [loading, setLoading] = useState(true);
  const [statusFilter, setStatusFilter] = useState<string>('');
  const [selectedPlan, setSelectedPlan] = useState<RecoveryPlanRecord | null>(null);
  const [disruptionDetail, setDisruptionDetail] = useState<DisruptionRecord | null>(null);
  const [approvalsDetail, setApprovalsDetail] = useState<ApprovalRecord[]>([]);
  const [loadingDetail, setLoadingDetail] = useState(false);

  const fetchPlans = async () => {
    try {
      setLoading(true);
      const params: any = {};
      if (statusFilter) params.status = statusFilter;
      const res = await apiClient.getRecoveryPlans(params);
      setPlans(res);

      if (selectedRecordId) {
        const found = res.find((p) => p.id === selectedRecordId);
        if (found) handleSelectPlan(found);
      }
    } catch (err) {
      console.error('Failed to load recovery plans:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchPlans();
  }, [statusFilter]);

  const handleSelectPlan = async (plan: RecoveryPlanRecord) => {
    setSelectedPlan(plan);
    setSelectedRecordId(plan.id);
    try {
      setLoadingDetail(true);
      const res = await apiClient.getRecoveryPlanDetail(plan.id);
      setDisruptionDetail(res.disruption);
      setApprovalsDetail(res.approvals);
    } catch (err) {
      console.error('Failed to load recovery plan detail:', err);
    } finally {
      setLoadingDetail(false);
    }
  };

  const columns: Column<RecoveryPlanRecord>[] = [
    {
      key: 'plan_code',
      header: 'Plan Code',
      accessor: (row) => row.plan_code,
      render: (row) => <span className="font-mono font-medium text-slate-800">{row.plan_code}</span>,
    },
    {
      key: 'title',
      header: 'Strategic Response Plan',
      accessor: (row) => row.title,
      render: (row) => (
        <div>
          <div className="font-semibold text-slate-900 line-clamp-1">{row.title}</div>
          <div className="text-[11px] text-slate-500">{row.disruption_title || 'General mitigation'}</div>
        </div>
      ),
    },
    {
      key: 'strategy_type',
      header: 'Strategy',
      accessor: (row) => row.strategy_type,
      render: (row) => (
        <span className="font-mono text-xs px-2 py-0.5 rounded bg-blue-50 text-blue-700 border border-blue-200">
          {row.strategy_type}
        </span>
      ),
    },
    {
      key: 'estimated_cost',
      header: 'Est. Cost',
      accessor: (row) => row.estimated_cost,
      render: (row) => (
        <span className="font-mono font-medium text-slate-900">
          ${row.estimated_cost.toLocaleString()}
        </span>
      ),
    },
    {
      key: 'time_to_recovery_days',
      header: 'Time to Recover',
      accessor: (row) => row.time_to_recovery_days,
      render: (row) => <span className="font-mono text-xs">{row.time_to_recovery_days} days</span>,
    },
    {
      key: 'confidence_score',
      header: 'Confidence',
      accessor: (row) => row.confidence_score,
      render: (row) => (
        <div className="flex items-center gap-1.5 font-mono text-xs text-slate-700">
          <div className="w-12 h-1.5 rounded-full bg-slate-100 overflow-hidden">
            <div
              className="h-full bg-emerald-500"
              style={{ width: `${Math.min(row.confidence_score, 100)}%` }}
            />
          </div>
          {row.confidence_score.toFixed(0)}%
        </div>
      ),
    },
    {
      key: 'status',
      header: 'Status',
      accessor: (row) => row.status,
      render: (row) => <StatusBadge status={row.status} size="sm" isFixture={row.is_fixture} />,
    },
  ];

  return (
    <div className="p-8 max-w-7xl mx-auto space-y-6 animate-fade-in">
      <PageHeader
        title="Recovery Action Plans"
        description="Candidate response strategies generated by the Consequence Simulation engine, balancing expediting spend against downtime penalties and secondary risk."
        breadcrumbs={[{ label: 'Recovery Plans' }]}
        actions={
          <button
            onClick={fetchPlans}
            disabled={loading}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-700 bg-white border border-slate-200 rounded-lg hover:bg-slate-50 transition"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
            Refresh
          </button>
        }
      />

      <DataTable
        columns={columns}
        data={plans}
        isLoading={loading}
        onRowClick={handleSelectPlan}
        searchPlaceholder="Search plans by code, strategy, or title..."
        emptyTitle="No Recovery Plans Generated"
        emptyDescription="No mitigation plans are currently staged. When disruptions are detected, the simulation agent formulates response options here."
        onSeedFixtures={seedFixtures}
        filterComponent={
          <select
            value={statusFilter}
            onChange={(e) => setStatusFilter(e.target.value)}
            className="text-xs bg-slate-50 border border-slate-200 rounded-lg px-2.5 py-1.5 text-slate-700 focus:outline-none focus:ring-1 focus:ring-blue-500"
          >
            <option value="">All Statuses</option>
            <option value="PENDING_APPROVAL">Pending Approval</option>
            <option value="APPROVED">Approved</option>
            <option value="EXECUTED">Executed</option>
            <option value="REJECTED">Rejected</option>
          </select>
        }
      />

      {/* Record Deep-Dive Drawer */}
      <RecordDrawer
        isOpen={!!selectedPlan}
        onClose={() => {
          setSelectedPlan(null);
          setSelectedRecordId(null);
        }}
        title={selectedPlan?.title || ''}
        subtitle={`Strategy: ${selectedPlan?.strategy_type} • Est Cost: $${(selectedPlan?.estimated_cost || 0).toLocaleString()}`}
        code={selectedPlan?.plan_code}
        status={selectedPlan?.status}
        isFixture={selectedPlan?.is_fixture}
        fields={[
          { label: 'Plan Reference', value: selectedPlan?.plan_code },
          { label: 'Mitigation Strategy', value: selectedPlan?.strategy_type },
          { label: 'Estimated Expenditure', value: `$${(selectedPlan?.estimated_cost || 0).toLocaleString()} USD` },
          { label: 'Recovery Horizon', value: `${selectedPlan?.time_to_recovery_days} calendar days` },
          { label: 'Agent Confidence Score', value: `${selectedPlan?.confidence_score.toFixed(1)}%` },
          {
            label: 'Secondary Consequence Assessment',
            value: selectedPlan?.secondary_risk_assessment || 'No secondary stockout risk projected.',
          },
          { label: 'Executive Summary', value: selectedPlan?.summary },
          { label: 'Execution Protocol Steps', value: selectedPlan?.execution_steps },
        ]}
        relatedSections={[
          {
            title: 'Underlying Disruption Event',
            items: disruptionDetail
              ? [
                  {
                    id: disruptionDetail.id,
                    title: disruptionDetail.title,
                    subtitle: `Category: ${disruptionDetail.category} • Region: ${disruptionDetail.affected_region}`,
                    badge: disruptionDetail.severity,
                    onClick: () => {
                      setSelectedPlan(null);
                      navigateToRecord('disruptions', disruptionDetail.id);
                    },
                  },
                ]
              : [],
            emptyText: 'No disruption linked to this recovery plan',
          },
          {
            title: 'Governance Sign-Off Requests',
            items: approvalsDetail.map((app) => ({
              id: app.id,
              title: app.title,
              subtitle: `Requested by: ${app.requested_by} • Risk Level: ${app.risk_level}`,
              badge: app.status,
              onClick: () => {
                setSelectedPlan(null);
                navigateToRecord('approvals', app.id);
              },
            })),
            emptyText: 'No executive approval requests queued',
          },
        ]}
        actions={
          selectedPlan?.status === 'PENDING_APPROVAL' ? (
            <button
              onClick={() => {
                setSelectedPlan(null);
                navigateToRecord('approvals', approvalsDetail[0]?.id || 1);
              }}
              className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-semibold text-white bg-blue-600 rounded-lg hover:bg-blue-700 transition"
            >
              Open Governance Approvals Queue
              <ArrowRight className="w-3.5 h-3.5" />
            </button>
          ) : undefined
        }
      />
    </div>
  );
};

